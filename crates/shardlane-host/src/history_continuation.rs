//! Host-owned History continuation planner and transaction.
//!
//! [INPUT]: a canonical History `ConversationId`, a required stable
//! operation id, an optional target Provider, an optional continuation
//! instruction, an optional Project override; runtime facts come from the
//! Herdr client and the History catalog.
//! [OUTPUT]: `plan_history_continuation` — a read-only plan in the strict
//! order AlreadyLive → NativeResume → ContextTransfer →
//! NeedsProjectSelection → Unsupported; plus `continue_history_conversation`
//! — the plan-driven execution transaction (reusing the M2 launch and M5
//! transfer engines and their operation ledger; AlreadyLive never creates a
//! duplicate Agent).
//! [POS]: plan M6 / audit AF-01/AF-02/AF-09/AF-10. Planning precedes any
//! runtime mutation; NeedsProjectSelection is returned when the Project
//! cannot be resolved safely. Remote and the native GUI only consume this
//! service and own no Continue policy.

